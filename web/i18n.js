function detectLang() {
  const raw = (
    navigator.language ||
    (navigator.languages && navigator.languages[0]) ||
    "en"
  ).toLowerCase();
  return raw.startsWith("bg") ? "bg" : "en";
}

export const LANG = detectLang();

export function t(key, vars) {
  const dict = STRINGS[LANG] || STRINGS.en;
  let s = dict[key];
  if (s === undefined) s = STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, v);
    }
  }
  return s;
}

export function tp(key, count) {
  const dict = STRINGS[LANG] || STRINGS.en;
  const s = dict[`${key}.${count === 1 ? "one" : "other"}`] ?? key;
  return s.replaceAll("{count}", count);
}

export function applyStatic(scope = document) {
  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
    if (el.hasAttribute("data-i18n-title")) {
      el.title = t(el.dataset.i18nTitle);
    }
  });
}